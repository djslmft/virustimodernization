"""Compile a bounded edit allowlist from the supplied, extracted XML definitions."""
import json
from pathlib import Path

base = Path(__file__).resolve().parent
schema = json.loads((base/'catalog/parameter-schema.json').read_text())
ui = json.loads((base/'original-ui/layout.json').read_text())
fields = next(m['bytes'] for m in schema['messages'] if m['id']=='VirusTI_Singledump')
offsets = {}
for f in fields:
    if f.get('type') == 'parameter': offsets.setdefault(f['content'], set()).add(int(f['index']))
offsets = {p: next(iter(v)) for p,v in offsets.items() if len(v)==1}
message_codes = {'cc':0x70, 'pp':0x71, 'Bank C (6E) Single-3':0x6e, 'Bank D (6F) Single-4':0x6f}
wire_messages = {0x70:'Bank A (70) Single-1',0x71:'Bank B (71) Single-2',0x6e:'Bank C (6E) Single-3',0x6f:'Bank D (6F) Single-4'}
wire = {}
for page, name in wire_messages.items():
    message = next(m for m in schema['messages'] if m['id']==name)
    for field in message['bytes']:
        for mapping in field['mappings']:
            if 'mapindex' in mapping: wire[(page,mapping['content'])] = int(mapping['mapindex'])
groups = {'Filter 1','Filter 2','Filters','Filter Envelope','Amp Envelope','Envelope 3','Envelope 4',
          'Oscillator 1','Oscillator 2','Oscillator 3','Oscillators','LFO 1','LFO 2','LFO 3','Patch Common',
          'Oscillator 1 HyperSaw','Oscillator 1 Wavetable','Oscillator 2 HyperSaw','Oscillator 2 Wavetable',
          'Suboscillator','Noise Oscillator','Ring Modulator','Unison','Velocity Response','Surround','Voice Saturation','Vocoder',
          'Delay','Reverb','EQ','Patch Distortion','Analog Boost','Chorus','Phaser','Filter Bank',
          'Input','Input Follower','Input Ring Modulator','Arpeggiator',
          'Assign Slot 1','Assign Slot 2','Assign Slot 3','Assign Slot 4','Assign Slot 5','Assign Slot 6'}
entries, skipped = [], []
for parameter in schema['parameters']:
    if parameter['group'] not in groups: continue
    path = parameter['group']+'/'+parameter['name']
    if 'Backup' in parameter['name']: continue
    page = message_codes.get(parameter.get('defaultmessage'))
    offset = offsets.get(path)
    if page is None or offset is None or parameter.get('part') != 'all': continue
    controller = int(parameter.get('controllerindex','-1'))
    minimum, maximum = int(parameter['minValue']), int(parameter['maxValue'])
    if wire.get((page,path)) != controller or not (0<=minimum<=maximum<=127): continue
    condition_name = parameter.get('condition','')
    condition = ui['conditions'].get(condition_name)
    guards = []
    if condition_name and not condition_name.endswith('/Immer sichtbar'):
        if not condition:
            skipped.append({'path':path,'reason':'condition not found'}); continue
        valid = True
        for test in condition['tests']:
            if test.get('param') not in offsets or test.get('type') not in ['equals','equal','inside','outside']:
                valid = False; break
            guards.append({'offset':offsets[test['param']], 'minimum':int(test['minvalue']), 'maximum':int(test['maxvalue']),
                           'kind':{'equals':0,'equal':0,'inside':1,'outside':2}[test['type']]})
        if not valid or len(guards)>8:
            skipped.append({'path':path,'reason':'condition requires unavailable live state'}); continue
    entries.append({'id':path,'group':parameter['group'],'name':parameter['name'],'offset':offset,'page':page,'controller':controller,
                    'minimum':minimum,'maximum':maximum,'valueList':parameter.get('valuelist',''),
                    'condition':condition_name,'guards':guards,'guardAnd':condition.get('operand')=='and' if condition else True,
                    'guardInvert':condition.get('result')=='invert' if condition else False})
assert any(e['id']=='Filter 1/Cutoff' and e['offset']==49 and e['controller']==40 for e in entries)
assert len({e['id'] for e in entries})==len(entries)
(base/'editable-parameters.json').write_text(json.dumps(entries,indent=2))
lines = ['// Generated by generate_editable.py from the supplied XML; do not hand-edit.',
         '#define GENERATED_EDIT_PARAMETER_COUNT %d' % len(entries),
         'typedef struct { int offset, minimum, maximum, kind; } EditGuard;',
         'typedef struct { const char *key; int offset, page, controller, minimum, maximum, guardCount, guardAnd, guardInvert; EditGuard guards[8]; } EditParameter;',
         'static const EditParameter editParameters[] = {']
for e in entries:
    guards = ','.join('{%d,%d,%d,%d}'%(g['offset'],g['minimum'],g['maximum'],g['kind']) for g in e['guards']) or '{0,0,0,0}'
    lines.append('{%s,%d,%d,%d,%d,%d,%d,%d,%d,{%s}},' % (json.dumps(e['id']),e['offset'],e['page'],e['controller'],e['minimum'],e['maximum'],len(e['guards']),e['guardAnd'],e['guardInvert'],guards))
lines += ['};','static const unsigned editParameterCount = sizeof(editParameters)/sizeof(editParameters[0]);']
(base/'EditableParameters.h').write_text('\n'.join(lines)+'\n')
(base/'editable-generation.json').write_text(json.dumps({'count':len(entries),'skipped':skipped},indent=2))
print(json.dumps({'editable':len(entries),'conditionalEntries':sum(bool(e['guards']) for e in entries),'skipped':skipped},indent=2))
